    #[test]
    fn extra_of_only_keeps_what_the_macro_cannot_carry() {
        let f = parse_fields("a:String:required:trim:email:sortable:read_only:immutable")
            .unwrap()
            .remove(0);
        let x = extra_of(&f, None).unwrap();
        assert_eq!(x.validators.len(), 1);
        assert_eq!(x.validators[0].rule, ValidatorSpec::Email);
        assert!(x.transforms.is_empty());
        assert!(x.sortable && x.read_only && x.immutable);
        // Everything is already on the base field: nothing extra.
        let mut base = FieldDesc::new("a", FieldType::String);
        base.sortable = true;
        base.read_only = true;
        base.immutable = true;
        let plain = parse_fields("a:String:required:sortable:read_only:immutable")
            .unwrap()
            .remove(0);
        assert!(extra_of(&plain, Some(&base)).is_none());
        // `tenant_id` is read-only by the macro already.
        let mut t = FieldDesc::new("tenant_id", FieldType::Uuid);
        t.read_only = true;
        assert!(extra_of(&t, None).is_none());
    }
