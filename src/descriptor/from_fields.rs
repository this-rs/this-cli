//! `--fields` grammar -> [`FieldDesc`], and [`EntityDesc`] -> template context.
//!
//! Grammar (one entry per field, entries separated by top-level commas):
//!
//! ```text
//! name:Type[:rule]*          rule = ident [ "(" args ")" ] [ "@create" | "@update" ]
//! email:String:required:email
//! age:Option<i32>:min_value(0):max_value(150)
//! sku:String:trim:uppercase:string_length(3,20):filter(eq,starts_with):sortable
//! status_code:String:in_list(draft|sent|paid)
//! ```
//!
//! The context the templates receive is DERIVED from the `EntityDesc` by
//! [`ModelRender::from_entity`]: the descriptor is the single source, the macro invocation
//! and the `DESCRIBED_EXTRA` literal are two renderings of it, and [`super::code`] reads
//! both back (`generated_descriptor_matches_code`).

use anyhow::{Context, Result, bail};
use serde::Serialize;
use this_descriptor::{
    Applies, EntityDesc, FieldDesc, FieldType, FilterOp, TransformRule, TransformSpec,
    ValidatorRule, ValidatorSpec, base_fields,
};

/// Rust types accepted in `--fields` (inside an optional `Option<...>`).
pub const SUPPORTED_TYPES: [&str; 9] = [
    "String", "f64", "f32", "i32", "i64", "u32", "u64", "bool", "Uuid",
];

/// Same mapping as `this_descriptor::FieldTypeOf` (what the macro probe yields).
pub fn rust_to_field_type(base: &str) -> Option<FieldType> {
    Some(match base {
        "String" => FieldType::String,
        "bool" => FieldType::Bool,
        "i8" | "i16" | "i32" => FieldType::I32,
        "i64" => FieldType::I64,
        "u8" | "u16" | "u32" => FieldType::U32,
        "u64" => FieldType::U64,
        "f32" => FieldType::F32,
        "f64" => FieldType::F64,
        "Uuid" | "uuid::Uuid" => FieldType::Uuid,
        "NaiveDate" | "chrono::NaiveDate" => FieldType::Date,
        "Value" | "serde_json::Value" => FieldType::Json,
        t if t.starts_with("DateTime<") || t.starts_with("chrono::DateTime<") => {
            FieldType::DateTime
        }
        _ => return None,
    })
}

/// `(FieldType, optional)` of a Rust type as written in a model (`Option<T>`, `Vec<T>`);
/// unknown types fall back to `json`, like the macro probe.
pub fn probe_rust_type(rust_type: &str) -> (FieldType, bool) {
    let t = rust_type.trim();
    if let Some(inner) = t.strip_prefix("Option<").and_then(|s| s.strip_suffix('>')) {
        return (probe_rust_type(inner).0, true);
    }
    if let Some(inner) = t.strip_prefix("Vec<").and_then(|s| s.strip_suffix('>')) {
        return (FieldType::List(Box::new(probe_rust_type(inner).0)), false);
    }
    (rust_to_field_type(t).unwrap_or(FieldType::Json), false)
}

/// Rust type to write in the model for a declared field.
pub fn rust_type_of(f: &FieldDesc) -> Result<String> {
    let base = match &f.ty {
        FieldType::String => "String",
        FieldType::Bool => "bool",
        FieldType::I32 => "i32",
        FieldType::I64 => "i64",
        FieldType::U32 => "u32",
        FieldType::U64 => "u64",
        FieldType::F32 => "f32",
        FieldType::F64 => "f64",
        FieldType::Uuid => "Uuid",
        other => bail!(
            "field `{}`: type `{}` cannot be generated by `this add entity`",
            f.name,
            other.label()
        ),
    };
    Ok(if f.optional {
        format!("Option<{base}>")
    } else {
        base.to_string()
    })
}

/// Split `s` on `sep` outside parentheses and quotes.
pub fn split_top(s: &str, sep: char) -> Vec<String> {
    let mut out = Vec::new();
    // Parentheses (rule arguments) and angle brackets (`Option<T>`) are counted apart:
    // inside a rule argument `<` / `>` are plain characters (`pattern(a>b)`), and a stray
    // one must not swallow the following fields.
    let mut parens = 0i32;
    let mut angles = 0i32;
    let mut quote: Option<char> = None;
    let mut cur = String::new();
    for c in s.chars() {
        match quote {
            Some(q) => {
                if c == q {
                    quote = None;
                }
                cur.push(c);
            }
            None => match c {
                '"' | '\'' => {
                    quote = Some(c);
                    cur.push(c);
                }
                '(' => {
                    parens += 1;
                    cur.push(c);
                }
                ')' => {
                    parens -= 1;
                    cur.push(c);
                }
                '<' if parens == 0 => {
                    angles += 1;
                    cur.push(c);
                }
                '>' if parens == 0 => {
                    angles -= 1;
                    cur.push(c);
                }
                c if c == sep && parens == 0 && angles == 0 => out.push(std::mem::take(&mut cur)),
                c => cur.push(c),
            },
        }
    }
    out.push(cur);
    out
}

fn unquote(s: &str) -> String {
    let t = s.trim();
    for q in ['"', '\''] {
        if t.len() >= 2 && t.starts_with(q) && t.ends_with(q) {
            return t[1..t.len() - 1].to_string();
        }
    }
    t.to_string()
}

/// One parsed rule token: `name(args)@on`.
#[derive(Debug, Clone, PartialEq)]
pub struct RuleToken {
    pub name: String,
    pub args: Vec<String>,
    pub on: Option<Applies>,
}

pub fn parse_rule_token(token: &str) -> Result<RuleToken> {
    let token = token.trim();
    let (body, on) = match token.rsplit_once('@') {
        Some((b, o)) if !o.contains(')') => {
            let on = Applies::from_macro_op(o.trim())
                .with_context(|| format!("`{token}`: expected @create or @update"))?;
            (b.trim(), Some(on))
        }
        _ => (token, None),
    };
    let (name, args) = match body.find('(') {
        Some(i) => {
            let Some(inner) = body[i + 1..].strip_suffix(')') else {
                bail!("`{token}`: unbalanced parentheses");
            };
            let name = body[..i].trim().to_string();
            // A regex or a date format is ONE argument, taken verbatim: splitting
            // `pattern(foo|bar)` on `|` kept only `foo`, a silently weaker validator.
            if RAW_ARG_RULES.contains(&name.as_str()) {
                let arg = unquote(inner);
                let args = if arg.is_empty() { vec![] } else { vec![arg] };
                return finish_token(name, args, on, token);
            }
            // `in_list(a|b|c)` and `in_list(a, b, c)` are both accepted.
            let sep = if inner.contains('|') { '|' } else { ',' };
            let args = split_top(inner, sep)
                .into_iter()
                .map(|a| unquote(&a))
                .filter(|a| !a.is_empty())
                .collect();
            (name, args)
        }
        None => (body.to_string(), vec![]),
    };
    finish_token(name, args, on, token)
}

/// Rules whose single argument is kept verbatim (no split on `,` or `|`).
const RAW_ARG_RULES: [&str; 3] = ["pattern", "regex", "date_format"];

fn finish_token(
    name: String,
    args: Vec<String>,
    on: Option<Applies>,
    token: &str,
) -> Result<RuleToken> {
    if name.is_empty() {
        bail!("empty rule in `{token}`");
    }
    Ok(RuleToken { name, args, on })
}

fn number(field: &str, rule: &str, arg: Option<&String>) -> Result<f64> {
    arg.with_context(|| format!("field `{field}`: `{rule}` needs a number"))?
        .parse::<f64>()
        .with_context(|| format!("field `{field}`: `{rule}` needs a number"))
}

/// Bound of min_value / max_value. An integer field gets an INTEGER bound: `check()`
/// refuses a float bound on an integer field (`this.descriptor.validator_type`).
fn bound(
    field: &str,
    rule: &str,
    arg: Option<&String>,
    integer: bool,
) -> Result<serde_json::Number> {
    if integer {
        let raw = arg.with_context(|| format!("field `{field}`: `{rule}` needs an integer"))?;
        if let Ok(i) = raw.parse::<i64>() {
            return Ok(i.into());
        }
        bail!("field `{field}`: `{rule}({raw})` needs an integer (integer field)");
    }
    let n = number(field, rule, arg)?;
    serde_json::Number::from_f64(n)
        .with_context(|| format!("field `{field}`: `{rule}` is not finite"))
}

fn default_filter_ops(ty: &FieldType) -> Vec<FilterOp> {
    let mut ops = vec![FilterOp::Eq, FilterOp::Ne, FilterOp::In];
    if ty.is_numeric() {
        ops.extend([FilterOp::Gt, FilterOp::Gte, FilterOp::Lt, FilterOp::Lte]);
    }
    if ty.is_textual() {
        ops.extend([FilterOp::Contains, FilterOp::StartsWith]);
    }
    ops
}

fn filter_op(field: &str, s: &str) -> Result<FilterOp> {
    serde_json::from_value(serde_json::Value::String(s.to_string())).map_err(|_| {
        anyhow::anyhow!(
            "field `{field}`: unknown filter operator `{s}` (eq, ne, gt, gte, lt, lte, in, contains, starts_with, is_null)"
        )
    })
}

/// Apply one rule token to a field.
pub fn apply_rule(f: &mut FieldDesc, tok: &RuleToken) -> Result<()> {
    let name = f.name.clone();
    let on = tok.on.unwrap_or(Applies::Always);
    let numeric = f.ty.is_numeric();
    let integer = matches!(
        f.ty,
        FieldType::I32 | FieldType::I64 | FieldType::U32 | FieldType::U64
    );
    let textual = f.ty.is_textual();
    let ty_label = f.ty.label();
    let need = |ok: bool, what: &str| -> Result<()> {
        if ok {
            Ok(())
        } else {
            bail!(
                "field `{name}` ({ty_label}): `{}` only applies to {what} fields",
                tok.name
            )
        }
    };
    let mut added: Vec<ValidatorRule> = Vec::new();
    let mut v = |rule: ValidatorSpec, on: Applies| added.push(ValidatorRule { rule, on });
    match tok.name.as_str() {
        // `required` keeps the legacy meaning of the macro grammar: on create.
        "required" => v(ValidatorSpec::Required, tok.on.unwrap_or(Applies::Create)),
        "optional" => v(ValidatorSpec::Optional, on),
        "positive" => {
            need(numeric, "numeric")?;
            v(ValidatorSpec::Positive, on)
        }
        "string_length" | "length" => {
            need(textual, "text")?;
            let [min, max] = tok.args.as_slice() else {
                bail!("field `{name}`: string_length(min, max)");
            };
            let min = min.parse().context("string_length: min")?;
            let max = max.parse().context("string_length: max")?;
            if min > max {
                bail!("field `{name}`: string_length({min}, {max}) has min > max");
            }
            v(ValidatorSpec::StringLength { min, max }, on)
        }
        "min_value" | "min" => {
            need(numeric, "numeric")?;
            let n = bound(&name, &tok.name, tok.args.first(), integer)?;
            v(ValidatorSpec::MinValue(n), on)
        }
        "max_value" | "max" => {
            need(numeric, "numeric")?;
            let n = bound(&name, &tok.name, tok.args.first(), integer)?;
            v(ValidatorSpec::MaxValue(n), on)
        }
        "in_list" | "one_of" => {
            if tok.args.is_empty() {
                bail!("field `{name}`: in_list needs at least one value");
            }
            v(ValidatorSpec::in_list_strings(tok.args.clone()), on)
        }
        "date_format" => {
            need(textual, "text")?;
            let fmt = tok
                .args
                .first()
                .with_context(|| format!("field `{name}`: date_format(\"%Y-%m-%d\")"))?;
            v(ValidatorSpec::DateFormat(fmt.clone()), on)
        }
        "pattern" | "regex" => {
            need(textual, "text")?;
            let re = tok
                .args
                .first()
                .with_context(|| format!("field `{name}`: pattern(\"^[A-Z]+$\")"))?;
            regex::Regex::new(re).with_context(|| format!("field `{name}`: invalid pattern"))?;
            v(ValidatorSpec::Pattern(re.clone()), on)
        }
        "email" => {
            need(textual, "text")?;
            v(ValidatorSpec::Email, on)
        }
        "url" => {
            need(textual, "text")?;
            v(ValidatorSpec::Url, on)
        }
        "trim" | "uppercase" | "lowercase" => {
            need(textual, "text")?;
            let rule = match tok.name.as_str() {
                "trim" => TransformSpec::Trim,
                "uppercase" => TransformSpec::Uppercase,
                _ => TransformSpec::Lowercase,
            };
            f.transforms.push(TransformRule { rule, on });
        }
        "round_decimals" => {
            need(numeric, "numeric")?;
            let n = tok
                .args
                .first()
                .and_then(|a| a.parse().ok())
                .with_context(|| format!("field `{name}`: round_decimals(2)"))?;
            f.transforms.push(TransformRule {
                rule: TransformSpec::RoundDecimals(n),
                on,
            });
        }
        "filter" | "filterable" => {
            let ops = if tok.args.is_empty() {
                default_filter_ops(&f.ty)
            } else {
                tok.args
                    .iter()
                    .map(|a| filter_op(&name, a))
                    .collect::<Result<Vec<_>>>()?
            };
            for op in ops {
                if !f.filterable.contains(&op) {
                    f.filterable.push(op);
                }
            }
        }
        "sortable" => f.sortable = true,
        "read_only" => f.read_only = true,
        "immutable" => f.immutable = true,
        other => bail!(
            "field `{name}`: unknown rule `{other}` (required, optional, positive, string_length, \
             min_value, max_value, in_list, date_format, pattern, email, url, trim, uppercase, \
             lowercase, round_decimals, filter, sortable, read_only, immutable)"
        ),
    }
    f.validators.extend(added);
    Ok(())
}

/// Parse the whole `--fields` value.
pub fn parse_fields(input: &str) -> Result<Vec<FieldDesc>> {
    let mut out: Vec<FieldDesc> = Vec::new();
    for entry in split_top(input, ',') {
        let entry = entry.trim();
        if entry.is_empty() {
            continue;
        }
        let parts = split_top(entry, ':');
        if parts.len() < 2 {
            bail!(
                "Invalid field format: '{}'. Expected 'name:Type' (e.g. 'sku:String', \
                 'email:String:required:email')",
                entry
            );
        }
        let name = parts[0].trim().to_string();
        let rust_type = parts[1].trim().to_string();
        let base = rust_type
            .strip_prefix("Option<")
            .and_then(|s| s.strip_suffix('>'))
            .unwrap_or(&rust_type);
        if !SUPPORTED_TYPES.contains(&base) {
            bail!(
                "Unsupported field type: '{}'. Supported types: {}",
                base,
                SUPPORTED_TYPES.join(", ")
            );
        }
        if !this_descriptor::naming::is_identifier(&name) {
            bail!("Invalid field name: '{name}' (expected snake_case)");
        }
        if out.iter().any(|f| f.name == name) {
            bail!("Field '{name}' declared twice");
        }
        let (ty, optional) = probe_rust_type(&rust_type);
        let mut f = FieldDesc::new(name, ty);
        f.optional = optional;
        for rule in &parts[2..] {
            apply_rule(&mut f, &parse_rule_token(rule)?)?;
        }
        out.push(f);
    }
    Ok(out)
}

/// Does any field carry a rule (validator, transform, query capability)?
pub fn has_rules(fields: &[FieldDesc]) -> bool {
    fields.iter().any(|f| {
        !f.validators.is_empty()
            || !f.transforms.is_empty()
            || !f.filterable.is_empty()
            || f.sortable
            || f.read_only
            || f.immutable
    })
}

/// The rules `this add entity --validated` used to hard-code in `model_validated.rs.tera`,
/// now expressed as descriptor rules (same macro output).
pub fn apply_legacy_validated_defaults(e: &mut EntityDesc) {
    use Applies::{Create, Update};
    for f in e.fields.iter_mut() {
        let float = matches!(f.ty, FieldType::F32 | FieldType::F64);
        if !f.optional {
            f.validators.push(ValidatorRule {
                rule: ValidatorSpec::Required,
                on: Create,
            });
            if float {
                f.validators.push(ValidatorRule {
                    rule: ValidatorSpec::Positive,
                    on: Create,
                });
            }
            f.validators.push(ValidatorRule {
                rule: ValidatorSpec::Optional,
                on: Update,
            });
            if float {
                f.validators.push(ValidatorRule {
                    rule: ValidatorSpec::Positive,
                    on: Update,
                });
            }
        }
        // The former template matched `rust_type == "String"` / `"f64"`: Option<_> excluded.
        if f.ty == FieldType::String && !f.optional {
            f.transforms.push(TransformRule {
                rule: TransformSpec::Trim,
                on: Create,
            });
        }
        if float && !f.optional {
            f.transforms.push(TransformRule {
                rule: TransformSpec::RoundDecimals(2),
                on: Create,
            });
            f.transforms.push(TransformRule {
                rule: TransformSpec::RoundDecimals(2),
                on: Update,
            });
        }
    }
    if let Some(status) = e.field_or_overlay_mut("status") {
        let list = || ValidatorSpec::in_list_strings(vec!["active".into(), "inactive".into()]);
        status.validators.extend([
            ValidatorRule {
                rule: ValidatorSpec::Required,
                on: Create,
            },
            ValidatorRule {
                rule: list(),
                on: Create,
            },
            ValidatorRule {
                rule: ValidatorSpec::Optional,
                on: Update,
            },
            ValidatorRule {
                rule: list(),
                on: Update,
            },
        ]);
        status.transforms.extend([
            TransformRule {
                rule: TransformSpec::Trim,
                on: Create,
            },
            TransformRule {
                rule: TransformSpec::Lowercase,
                on: Create,
            },
            TransformRule {
                rule: TransformSpec::Trim,
                on: Update,
            },
            TransformRule {
                rule: TransformSpec::Lowercase,
                on: Update,
            },
        ]);
    }
}

