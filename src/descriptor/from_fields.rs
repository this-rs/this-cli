fn fmt_number(n: &serde_json::Number) -> String {
    match n.as_f64() {
        Some(v) if v.fract() == 0.0 && v.abs() < 1e15 => format!("{}", v as i64),
        Some(v) => format!("{v}"),
        None => n.to_string(),
    }
}

fn rust_str(s: &str) -> String {
    format!("{s:?}")
}

/// Macro-grammar spelling of a validator, `None` when the grammar of
/// `impl_data_entity_validated!` cannot express it (it then goes to `DESCRIBED_EXTRA`).
pub fn macro_validator(v: &ValidatorSpec) -> Option<String> {
    Some(match v {
        ValidatorSpec::Required => "required".into(),
        ValidatorSpec::Optional => "optional".into(),
        ValidatorSpec::Positive => "positive".into(),
        ValidatorSpec::StringLength { min, max } => format!("string_length({min}, {max})"),
        // The macro builds `max_value_f64(..)`: a FLOAT bound, which `check()` refuses on an
        // integer field. Integer bounds therefore go to DESCRIBED_EXTRA.
        ValidatorSpec::MaxValue(n) if n.is_f64() => format!("max_value({})", fmt_number(n)),
        ValidatorSpec::InList(values) => {
            let strs: Option<Vec<String>> =
                values.iter().map(|v| v.as_str().map(rust_str)).collect();
            format!("in_list({})", strs?.join(", "))
        }
        ValidatorSpec::DateFormat(f) => format!("date_format({})", rust_str(f)),
        _ => return None,
    })
}

pub fn macro_transform(t: &TransformSpec) -> Option<String> {
    Some(match t {
        TransformSpec::Trim => "trim".into(),
        TransformSpec::Uppercase => "uppercase".into(),
        TransformSpec::Lowercase => "lowercase".into(),
        TransformSpec::RoundDecimals(n) => format!("round_decimals({n})"),
        _ => return None,
    })
}

/// `field: [rules]` line of a `create:` / `update:` block.
#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct RuleLine {
    pub field: String,
    pub rules: String,
}

#[derive(Debug, Clone, Serialize, Default, PartialEq)]
pub struct OpBlocks {
    pub create: Vec<RuleLine>,
    pub update: Vec<RuleLine>,
}

#[derive(Debug, Clone, Serialize)]
pub struct MacroField {
    pub name: String,
    pub rust_type: String,
    pub is_optional: bool,
}

/// Everything the entity templates need, derived from ONE `EntityDesc`.
#[derive(Debug, Clone, Serialize)]
pub struct ModelRender {
    /// Struct fields (base-field overlays such as `status` excluded).
    pub fields: Vec<MacroField>,
    pub indexed_fields: Vec<String>,
    pub validate: OpBlocks,
    pub filters: OpBlocks,
    /// `impl_data_entity_validated!` needed (some rule fits the macro grammar).
    pub validated: bool,
    /// JSON array of partial `FieldDesc` the macro grammar cannot carry; empty if none.
    pub extra_json: String,
    /// Raw-string hashes so that `extra_json` never closes its literal early.
    pub extra_hashes: String,
}

fn block_for<T>(
    fields: &[FieldDesc],
    rules: impl Fn(&FieldDesc) -> &Vec<T>,
    on_of: impl Fn(&T) -> Applies,
    spell: impl Fn(&T) -> Option<String>,
) -> OpBlocks {
    let mut out = OpBlocks::default();
    for op in [Applies::Create, Applies::Update] {
        for f in fields {
            let words: Vec<String> = rules(f)
                .iter()
                .filter(|r| on_of(r).covers(op))
                .filter_map(&spell)
                .collect();
            if !words.is_empty() {
                let line = RuleLine {
                    field: f.name.clone(),
                    rules: words.join(" "),
                };
                match op {
                    Applies::Create => out.create.push(line),
                    _ => out.update.push(line),
                }
            }
        }
    }
    out
}

/// Partial `FieldDesc` carrying what the macro grammar cannot express, or `None`.
pub fn extra_of(f: &FieldDesc, base: Option<&FieldDesc>) -> Option<FieldDesc> {
    let mut x = FieldDesc::new(f.name.clone(), f.ty.clone());
    // An overlay of a base field (`status`, `name`) starts from the base field: only what
    // it ADDS is extra (the macro overlay copies the base the same way).
    let base_has_op = |op: &FilterOp| base.is_some_and(|b| b.filterable.contains(op));
    x.validators = f
        .validators
        .iter()
        .filter(|r| macro_validator(&r.rule).is_none())
        .cloned()
        .collect();
    x.transforms = f
        .transforms
        .iter()
        .filter(|r| macro_transform(&r.rule).is_none())
        .cloned()
        .collect();
    x.filterable = f
        .filterable
        .iter()
        .filter(|o| !base_has_op(o))
        .copied()
        .collect();
    x.sortable = f.sortable && !base.is_some_and(|b| b.sortable);
    // `tenant_id` is read-only by the macro already.
    x.read_only = f.read_only
        && f.name != this_descriptor::entity::TENANT_ID
        && !base.is_some_and(|b| b.read_only);
    x.immutable = f.immutable && !base.is_some_and(|b| b.immutable);
    let empty = x.validators.is_empty()
        && x.transforms.is_empty()
        && x.filterable.is_empty()
        && !x.sortable
        && !x.read_only
        && !x.immutable;
    (!empty).then_some(x)
}

impl ModelRender {
    pub fn from_entity(e: &EntityDesc) -> Result<Self> {
        let base: Vec<&str> = base_fields(e.kind)
            .iter()
            .map(|b| b.name.as_str())
            .collect();
        let mut fields = Vec::new();
        for f in e.fields.iter().filter(|f| !base.contains(&f.name.as_str())) {
            fields.push(MacroField {
                name: f.name.clone(),
                rust_type: rust_type_of(f)?,
                is_optional: f.optional,
            });
        }
        let validate = block_for(
            &e.fields,
            |f| &f.validators,
            |r| r.on,
            |r| macro_validator(&r.rule),
        );
        let filters = block_for(
            &e.fields,
            |f| &f.transforms,
            |r| r.on,
            |r| macro_transform(&r.rule),
        );
        let extras: Vec<FieldDesc> = e
            .fields
            .iter()
            .filter_map(|f| extra_of(f, base_fields(e.kind).iter().find(|b| b.name == f.name)))
            .collect();
        let extra_json = if extras.is_empty() {
            String::new()
        } else {
            serde_json::to_string(&extras)?
        };
        let mut extra_hashes = "#".to_string();
        while extra_json.contains(&format!("\"{extra_hashes}")) {
            extra_hashes.push('#');
        }
        let validated = validate != OpBlocks::default() || filters != OpBlocks::default();
        Ok(Self {
            fields,
            indexed_fields: e.indexed.clone(),
            validate,
            filters,
            validated,
            extra_json,
            extra_hashes,
        })
    }
}

