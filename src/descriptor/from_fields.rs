    #[test]
    fn bare_filter_uses_type_defaults() {
        let eq_ne_in = vec![FilterOp::Eq, FilterOp::Ne, FilterOp::In];
        let f = parse_fields("n:i32:filter,s:String:filterable,b:bool:filter").unwrap();
        assert_eq!(
            f[0].filterable,
            vec![
                FilterOp::Eq,
                FilterOp::Ne,
                FilterOp::In,
                FilterOp::Gt,
                FilterOp::Gte,
                FilterOp::Lt,
                FilterOp::Lte
            ]
        );
        assert_eq!(
            f[1].filterable,
            vec![
                FilterOp::Eq,
                FilterOp::Ne,
                FilterOp::In,
                FilterOp::Contains,
                FilterOp::StartsWith
            ]
        );
        assert_eq!(f[2].filterable, eq_ne_in);
        // Repeating an operator does not duplicate it.
        let f = parse_fields("s:String:filter(eq):filter(eq,ne)").unwrap();
        assert_eq!(f[0].filterable, vec![FilterOp::Eq, FilterOp::Ne]);
        let e = err_of("s:String:filter(between)");
        assert!(e.contains("unknown filter operator `between`"), "{e}");
    }

